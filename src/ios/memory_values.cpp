std::optional<IosMemoryValues> ios_memory_values(u32 ios) {
    for (const auto& v : kTable)
        if (v.ios == ios) return v;
    return std::nullopt;
}

bool write_ios_memory_values(mem::Bus& bus, const IosMemoryValues& v) {
    constexpr u32 kMem1 = 0x01800000U, kMem2 = 0x04000000U, kPlaceholder = 0xDEADBEEFU;
    const std::vector<u8> zero(0x4000);
    if (bus.dma_write(0, zero) != mem::BusStatus::Ok) return false;
    const u32 ipc_begin = v.mem2_end - 0x20000U;
    const std::pair<u32, u32> words[] = {
        {0x3100, kMem1}, {0x3104, kMem1}, {0x3108, 0x80000000U + kMem1}, {0x310C, 0}, {0x3110, 0x80000000U + kMem1},
        {0x3114, kPlaceholder}, {0x3118, kMem2}, {0x311C, kMem2}, {0x3120, v.mem2_end}, {0x3124, 0x90000800U},
        {0x3128, ipc_begin}, {0x312C, kPlaceholder}, {0x3130, ipc_begin}, {0x3134, v.mem2_end}, {0x3138, 0x11},
        {0x313C, kPlaceholder}, {0x3140, v.version}, {0x3144, v.date}, {0x3148, v.reserved_begin},
        {0x314C, v.reserved_end}, {0x3150, kPlaceholder}, {0x3154, kPlaceholder}, {0x3158, v.ram_vendor},
        {0x3160, v.sysmenu_sync}, {0x28, kMem1}, {0x30, 0}, {0x34, 0x80000000U + kMem1}, {0xF0, kMem1},
    };
    for (const auto& [a, x] : words)
        if (bus.write32(a, x) != mem::BusStatus::Ok) return false;
    return bus.write8(0x315C, 0xDE) == mem::BusStatus::Ok && bus.write8(0x315D, 0xAD) == mem::BusStatus::Ok &&
           bus.write16(0x315E, 0xBEEF) == mem::BusStatus::Ok;
}

